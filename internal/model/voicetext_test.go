package model

import "testing"

func TestParseVoiceTranscript(t *testing.T) {
	// 取自真实语音消息的 packed_info_data
	blob := []byte{
		0x08, 0x04, 0x10, 0x05, 0x2a, 0x28, 0x08, 0x02, 0x12, 0x24,
		0xe4, 0xb9, 0xb0, 0xe4, 0xb8, 0xaa, 0xe5, 0xa4, 0xa7, 0xe8, 0x9b, 0x8b,
		0xe7, 0x9a, 0x84, 0xef, 0xbc, 0x8c, 0xe4, 0xba, 0xba, 0xe5, 0xae, 0xb6,
		0xe6, 0x97, 0xa9, 0xe8, 0xb5, 0xb0, 0xe4, 0xba, 0x86, 0xe3, 0x80, 0x82,
	}
	if got, want := ParseVoiceTranscript(blob), "买个大蛋的，人家早走了。"; got != want {
		t.Fatalf("got %q want %q", got, want)
	}
	if ParseVoiceTranscript(nil) != "" {
		t.Fatal("nil 应返回空")
	}
	if ParseVoiceTranscript([]byte{0x08, 0x04}) != "" {
		t.Fatal("无 field5 应返回空")
	}
}
